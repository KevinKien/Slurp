export type Kind = "vuln" | "safe" | "noise";
export type Case = {
  id: string;
  group: string;
  kind: Kind;
  title: string;
  request: (origin: string) => HttpRequest;
  parameter?: ScanParameter;
  /** Checks that should report this case. */
  expect: string[];
  /** Checks whose report here is acceptable (not counted as a false positive). */
  tolerate?: string[];
  /** Ambient checks (header, cookie and reflection observations) that must stay silent on this case. */
  strict?: string[];
};

const q = (name: string): ScanParameter => ({ kind: "query", name, occurrence: 0 });
const pointer = (p: string): ScanParameter => ({ kind: "json", pointer: p });
const get =
  (path: string, headers: Record<string, string> = {}) =>
  (origin: string): HttpRequest => ({
    method: "GET",
    url: `${origin}${path}`,
    headers: { accept: "*/*", ...headers },
    body: "",
  });
/** Reached by name: the CORS host-name checks do not build variants of an IP address. */
const getLocalhost =
  (path: string, headers: Record<string, string> = {}) =>
  (origin: string): HttpRequest => ({
    method: "GET",
    url: `${origin.replace("127.0.0.1", "localhost")}${path}`,
    headers: { accept: "*/*", ...headers },
    body: "",
  });
const post =
  (path: string, body: string, type: string, headers: Record<string, string> = {}) =>
  (origin: string): HttpRequest => ({
    method: "POST",
    url: `${origin}${path}`,
    headers: { "content-type": type, ...headers },
    body,
  });
const postJson = (path: string, value: unknown, headers: Record<string, string> = {}) =>
  post(path, JSON.stringify(value), "application/json", headers);
const token = (secret: string) =>
  signJwt({ sub: "alice", iat: 1_700_000_000, exp: 4_000_000_000 }, secret);
const form = (path: string, fields: Record<string, string>) =>
  post(path, new URLSearchParams(fields).toString(), "application/x-www-form-urlencoded");
const f = (name: string): ScanParameter => ({ kind: "form", name, occurrence: 0 });
const multipart =
  (path: string) =>
  (origin: string): HttpRequest => {
    const boundary = "----benchboundary";
    const body = `--${boundary}\r\nContent-Disposition: form-data; name="description"\r\n\r\nholiday\r\n--${boundary}\r\nContent-Disposition: form-data; name="file"; filename="photo.jpg"\r\nContent-Type: image/jpeg\r\n\r\nÿØÿàJFIFdata\r\n--${boundary}--\r\n`;
    return {
      method: "POST",
      url: `${origin}${path}`,
      headers: { "content-type": `multipart/form-data; boundary=${boundary}` },
      body,
    };
  };


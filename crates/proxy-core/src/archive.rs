//! Workspace export/import as `.slurp` files.
//!
//! A `.slurp` file is a ZIP archive holding `manifest.json` plus one NDJSON file per table
//! (`data/<table>.ndjson`, one JSON object per row; BLOBs are `{"$b64": "..."}`). Import always
//! creates a new workspace, so it can never overwrite existing data.
use crate::storage::{TrafficStorage, Workspace, DEFAULT_WORKSPACE_ID, TEMP_WORKSPACE_ID};
use base64::Engine;
use chrono::Utc;
use rusqlite::types::{Value as Sql, ValueRef};
use rusqlite::{params_from_iter, Connection};
use serde::{Deserialize, Serialize};
use serde_json::{json, Map, Value};
use std::collections::HashMap;
use std::io::{BufRead, Read, Seek, Write};
use uuid::Uuid;

pub const MAGIC: &str = "slurp-workspace";
pub const FORMAT_VERSION: u32 = 1;
const MAX_LINE: u64 = 64 * 1024 * 1024;
const MAX_TOTAL: u64 = 32 * 1024 * 1024 * 1024;
const MAX_MANIFEST: u64 = 1024 * 1024;
const BATCH_ROWS: usize = 200;
const BATCH_BYTES: usize = 8 * 1024 * 1024;
const REDACTED: &str = "[redacted]";

#[derive(Debug)]
pub enum ArchiveError {
    /// The file is not a usable `.slurp` archive.
    Invalid(String),
    NotFound,
    Other(anyhow::Error),
}

impl std::fmt::Display for ArchiveError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Invalid(message) => write!(f, "{message}"),
            Self::NotFound => write!(f, "workspace not found"),
            Self::Other(e) => write!(f, "{e}"),
        }
    }
}

impl std::error::Error for ArchiveError {}

fn invalid(message: impl Into<String>) -> ArchiveError {
    ArchiveError::Invalid(message.into())
}

impl From<rusqlite::Error> for ArchiveError {
    fn from(e: rusqlite::Error) -> Self {
        match &e {
            rusqlite::Error::SqliteFailure(err, _) if err.code == rusqlite::ErrorCode::ConstraintViolation => {
                invalid("the file contains rows that violate the workspace schema")
            }
            _ => Self::Other(e.into()),
        }
    }
}
impl From<std::io::Error> for ArchiveError {
    fn from(e: std::io::Error) -> Self {
        Self::Other(e.into())
    }
}
impl From<zip::result::ZipError> for ArchiveError {
    fn from(e: zip::result::ZipError) -> Self {
        invalid(format!("not a valid .slurp archive: {e}"))
    }
}
impl From<anyhow::Error> for ArchiveError {
    fn from(e: anyhow::Error) -> Self {
        Self::Other(e)
    }
}

#[derive(Debug, Clone, Copy)]
pub struct ExportOptions {
    /// Include authentication profiles (cookies, tokens, headers).
    pub include_profiles: bool,
    /// Include Intruder sources, payloads, runs and results.
    pub include_intruder: bool,
    /// Mask sensitive header and token values; profiles are then never exported.
    pub redact_secrets: bool,
}

impl Default for ExportOptions {
    fn default() -> Self {
        Self { include_profiles: true, include_intruder: true, redact_secrets: false }
    }
}

#[derive(Debug, Clone, Serialize)]
pub struct ImportSummary {
    pub workspace: Workspace,
    pub rows: u64,
}

#[derive(Clone, Copy, PartialEq)]
enum Scope {
    /// Rows carry a `workspace_id` column.
    Direct,
    /// `websocket_frames`: scoped through `connection_id`.
    Frames,
    /// `websocket_requests`: its id is a connection id.
    Requests,
}

#[derive(Clone, Copy, PartialEq)]
enum Group {
    Core,
    Profiles,
    Intruder,
}

struct Spec {
    name: &'static str,
    columns: &'static [&'static str],
    /// Columns that order rows and let export resume after each batch.
    keys: &'static [&'static str],
    scope: Scope,
    group: Group,
    /// Text columns holding JSON; validated on import, redacted and id-remapped when needed.
    json: &'static [&'static str],
    /// Columns not copied on import (autogenerated).
    skip: &'static [&'static str],
}

